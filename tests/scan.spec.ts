test('real local photo OCR is editable, reviewed, saved and available to transpose after reload',async({page},testInfo)=>{
  test.setTimeout(90000)
  const network:string[]=[],uploads:string[]=[]
  page.on('request',request=>{network.push(request.url());if(request.method()==='POST')uploads.push(request.url())})
  await page.goto('/')
  await page.getByRole('button',{name:'Scan photo / PDF',exact:true}).click()
  expect(network.some(url=>url.includes('/scan-assets/'))).toBe(false)
  const image=await scanImage(page)
  await page.getByLabel('Photo or PDF',{exact:true}).setInputFiles({name:'photo.png',mimeType:'image/png',buffer:Buffer.from(image.png,'base64')})
  const editor=page.getByRole('textbox',{name:'Recognized text — edit before importing',exact:true})
  await expect(editor).toHaveValue(/Morning light across the sea/,{timeout:60000})
  expect(network.some(url=>url.includes('/scan-assets/ocr/') && url.includes('eng.traineddata'))).toBe(true)
  expect(network.filter(url=>!url.startsWith('data:')&&!url.startsWith('blob:')).every(url=>new URL(url).hostname==='127.0.0.1')).toBe(true)
  expect(uploads).toEqual([])
  expect(await page.evaluate(()=>localStorage.getItem('mm:user-songs'))).toBeNull()
  await editor.fill(correctedScan)
  await page.screenshot({path:testInfo.outputPath('scan-desktop-review.png'),fullPage:true})
  const accessibility=await new AxeBuilder({page}).analyze()
  expect(accessibility.violations.filter(violation=>['serious','critical'].includes(violation.impact??''))).toEqual([])
  await page.getByRole('button',{name:'Review import',exact:true}).click()
  await expect(page.getByRole('button',{name:'Confirm import',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Confirm artist and title',exact:true}).click()
  await page.getByRole('button',{name:'Confirm import',exact:true}).click()
  await expect(page.getByText('Import complete: 1 added, 0 already present.',{exact:true})).toBeVisible()
  await page.reload()
  await openUserSong(page,'Scan Reader')
  await expect(page.locator('.mm-chord-sheet')).toContainText('Morning light across the sea')
  await expect(page.locator('.mm-chord-diag').filter({hasText:'Am'})).toHaveCount(1)
  await page.getByRole('button',{name:'Up one semitone',exact:true}).click()
  await expect(page.locator('.mm-chord-diag').filter({hasText:'C#'})).toHaveCount(1)
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('mm:user-songs')!) as {arrangements:{source:{text:string}}[]}[])
  expect(saved[0].arrangements[0].source.text).toBe(correctedScan)
})

