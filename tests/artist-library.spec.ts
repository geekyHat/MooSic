import catalogue from '../src/content/publicdomain/index.json' with {type:'json'}
import { expect, test } from './fixtures/browser'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function createSong(page: Page, name: string, artist: string) {
  await page.getByRole('button', {name: 'Editor', exact: true}).click()
  await page.getByRole('button', {name: '+ New song', exact: true}).click()
  await page.getByLabel('Artist', {exact: true}).fill(artist)
  await page.getByLabel('Song name', {exact: true}).fill(name)
  await page.getByRole('button', {name: 'Create', exact: true}).click()
  await expect(page.getByRole('heading', {name, exact: true})).toBeVisible()
}

test('artist suggestions connect editor, existing library artist and practice on mobile', async ({page}, testInfo) => {
  await page.setViewportSize({width: 375, height: 900})
  await page.goto('/')
  await page.getByRole('button', {name: 'Editor', exact: true}).click()
  await page.getByRole('button', {name: '+ New song', exact: true}).click()
  const artist = page.getByLabel('Artist', {exact: true})
  await expect(artist).toBeFocused()
  await artist.fill('Traditonal')
  await expect(page.getByRole('group', {name: 'Matching artists'}).getByRole('button', {name: 'Traditional', exact: true})).toBeVisible()
  await page.screenshot({path: testInfo.outputPath('artist-suggestions-mobile.png')})
  const accessibility = await new AxeBuilder({page}).analyze()
  expect(accessibility.violations.filter(violation => ['serious', 'critical'].includes(violation.impact ?? ''))).toEqual([])
  await artist.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(artist).toHaveValue('Traditional')
  await page.getByLabel('Song name', {exact: true}).fill('A new folk song')
  await page.getByRole('button', {name: 'Create', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'A new folk song', exact: true})).toBeVisible()
  await page.getByRole('button', {name: /Chords \+ lyrics/}).click()
  await page.getByLabel('Lyric line, Bar 1', {exact: true}).fill('Original words')
  await page.getByRole('button', {name: '+ Save', exact: true}).click()
  await expect(page.getByText('1 arrangement(s) saved', {exact: true})).toBeVisible()
  // The main Practice tab must use the saved song, without the editor's shortcut.
  await page.getByRole('navigation').getByRole('button', {name: 'Practice', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'A new folk song', exact: true})).toBeVisible()
  await expect(page.locator('.mm-chord-sheet')).toContainText('Original words')
  await page.getByRole('button', {name: 'Library', exact: true}).click()
  await expect(page.locator('.mm-artist')).toHaveCount(catalogue.artists.length)
  const card = page.locator('.mm-artist').filter({hasText: 'Traditional'})
  await expect(card).toHaveCount(1)
  await expect(card).toContainText(`${catalogue.artists.find(artist=>artist.meta.id==='traditional')!.songs.length+1} songs`)
  await card.getByRole('button', {name: 'Open', exact: true}).click()
  await page.locator('.mm-song').filter({hasText: 'A new folk song'}).getByRole('button', {name: 'Edit in editor', exact: true}).click()
  await expect(page.getByLabel('Artist', {exact: true})).toHaveValue('Traditional')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('new artists and metadata-only songs appear immediately and can be completed from the library', async ({page}) => {
  await page.goto('/')
  await createSong(page, 'New composition', 'José González')
  await page.getByRole('button', {name: 'Library', exact: true}).click()
  await page.locator('.mm-artist').filter({hasText: 'José González'}).getByRole('button', {name: 'Open', exact: true}).click()
  const song = page.locator('.mm-song').filter({hasText: 'New composition'})
  await expect(song).toContainText('Details saved. Add an arrangement')
  await song.getByRole('button', {name: 'Edit in editor', exact: true}).click()
  await page.getByLabel('Artist', {exact: true}).fill('New artist')
  await page.getByRole('button', {name: 'Save details', exact: true}).click()
  await expect(page.getByText('Song saved.', {exact: true})).toBeVisible()
  await page.reload()
  await page.goto('/#/library')
  await expect(page.locator('.mm-artist').filter({hasText: 'José González'})).toHaveCount(0)
  await page.locator('.mm-artist').filter({hasText: 'New artist'}).getByRole('button', {name: 'Open', exact: true}).click()
  await expect(page.locator('.mm-song')).toContainText('New composition')
  await createSong(page, 'Second composition', ' NEW   ARTIST ')
  await expect(page.getByLabel('Artist', {exact: true})).toHaveValue('New artist')
  await page.getByRole('button', {name: 'Library', exact: true}).click()
  await page.goto('/#/library')
  const card = page.locator('.mm-artist').filter({hasText: 'New artist'})
  await expect(card).toHaveCount(1)
  await expect(card).toContainText('2 songs')
})

test('existing editor songs are restored to the library with older saved plugin settings', async ({page}) => {
  await page.addInitScript(() => {
    if (localStorage.getItem('mm:user-songs')) return
    localStorage.setItem('mm:settings', JSON.stringify({locale: 'en', enabled: ['instrument-guitar', 'theme-default', 'parser-abc', 'renderer-tab', 'content-publicdomain']}))
    localStorage.setItem('mm:user-songs', JSON.stringify([{id: 'legacy-song', name: 'Previously hidden song', artist: ' TRADITIONAL ', genre: '', createdAt: 1,
      arrangements: [{id: 'arr', kind: 'lyrics', name: 'Lyrics', bars: 1, beatsPerBar: 4, tempo: 100, chordBars: [{chord: 'Am', lyric: 'Recovered words'}]}]}]))
  })
  await page.goto('/')
  await expect(page.locator('.mm-artist')).toHaveCount(catalogue.artists.length)
  await page.locator('.mm-artist').filter({hasText: 'Traditional'}).getByRole('button', {name: 'Open', exact: true}).click()
  const song = page.locator('.mm-song').filter({hasText: 'Previously hidden song'})
  await expect(song).toBeVisible()
  await song.getByRole('button', {name: 'Open', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Previously hidden song', exact: true})).toBeVisible()
  await expect(page.locator('.mm-chord-sheet')).toContainText('Recovered words')
  await page.reload()
  await page.goto('/#/library')
  await expect(page.locator('.mm-artist').filter({hasText: 'Traditional'})).toContainText(`${catalogue.artists.find(artist=>artist.meta.id==='traditional')!.songs.length+1} songs`)
})

test('saving from the editor reconnects a disabled local catalog and offers local artist suggestions', async ({page}) => {
  await page.goto('/')
  await createSong(page, 'First song', 'Local Band')
  await page.getByRole('button', {name: 'Settings', exact: true}).click()
  await page.getByRole('button', {name: 'My songs (user editor): Enabled', exact: true}).click()
  await page.getByRole('button', {name: 'Editor', exact: true}).click()
  await page.getByRole('button', {name: '+ New song', exact: true}).click()
  await page.getByLabel('Artist', {exact: true}).fill('Local Bnd')
  await page.getByRole('group', {name: 'Matching artists'}).getByRole('button', {name: 'Local Band', exact: true}).click()
  await page.getByLabel('Song name', {exact: true}).fill('Second song')
  await page.getByRole('button', {name: 'Create', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Second song', exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'Library', exact: true}).click()
  await expect(page.locator('.mm-artist').filter({hasText: 'Local Band'})).toContainText('2 songs')
})
