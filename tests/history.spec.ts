async function seed(page:Page,songs=records){
  await page.addInitScript(songs=>{if(!localStorage.getItem('mm:user-songs'))localStorage.setItem('mm:user-songs',JSON.stringify(songs))},songs)
  await page.goto('/')
  await expect(page.locator('.mm-artist').filter({hasText:'History Artist'})).toBeVisible()
}
const artist=(page:Page)=>page.locator('.mm-artist').filter({hasText:'History Artist'}).getByRole('button',{name:'Open',exact:true})
const open=(page:Page,name:string)=>page.locator('.mm-song').filter({has:page.getByRole('heading',{name,exact:true})}).getByRole('button',{name:'Open',exact:true})
const view=(page:Page,name:string)=>page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('button',{name,exact:true})

