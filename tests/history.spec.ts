test('browser Back protects an import draft, then closes the panel after explicit discard',async({page})=>{
  await seed(page)
  await page.getByRole('button',{name:'Import files',exact:true}).click()
  await page.getByLabel('Music files',{exact:true}).setInputFiles({name:'draft.cho',mimeType:'text/plain',buffer:Buffer.from('{title: Draft}\n{artist: Draft Artist}\n[Am]Unsaved import')})
  const url=page.url()
  await page.goBack()
  await page.getByRole('button',{name:'Keep editing',exact:true}).click()
  await expect(page).toHaveURL(url)
  await expect(page.getByLabel('Title — draft.cho',{exact:true})).toHaveValue('Draft')
  await page.goBack()
  await page.getByRole('button',{name:'Discard changes',exact:true}).click()
  await expect(page.getByLabel('Title — draft.cho',{exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Import files',exact:true})).toBeEnabled()
  await page.goForward()
  await expect(page.getByLabel('Music files',{exact:true})).toBeAttached()
  await expect(page.getByRole('region',{name:'Import preview',exact:true})).toHaveCount(0)
})

