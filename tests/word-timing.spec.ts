import {expect,test} from './fixtures/browser'

test('existing word timing stays editable while practice uses static lyrics and autoscroll',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Editor',exact:true}).click()
 await page.getByRole('button',{name:'+ New song',exact:true}).click()
 await page.getByLabel('Song name',{exact:true}).fill('Timing study')
 await page.getByRole('button',{name:'Create',exact:true}).click()
 await page.getByRole('button',{name:/Chords \+ lyrics/}).click()
 await page.getByLabel('Lyric line, Bar 1',{exact:true}).fill('Una luce')
 await page.getByText('Word timing (beats, editable), Bar 1',{exact:true}).first().click()
 await page.getByRole('button',{name:'Generate approximate timing',exact:true}).first().click()
 const start=page.getByLabel('Start beat, word 2',{exact:true})
 await expect(start).toHaveValue('2')
 await page.getByRole('button',{name:'+ Save',exact:true}).click()
 await page.getByRole('button',{name:'Practice',exact:true}).last().click()
 await expect(page.locator('.mm-chord-sheet')).toContainText('Una luce')
 await expect(page.getByRole('button',{name:'▶ Autoscroll',exact:true})).toBeVisible()
 await expect(page.locator('.mm-chord-sheet [aria-current]')).toHaveCount(0)
 await page.getByRole('button',{name:'Editor',exact:true}).click()
 await page.getByRole('button',{name:/Timing study/}).click()
 await page.getByRole('button',{name:'Edit',exact:true}).click()
 await page.getByText('Word timing (beats, editable), Bar 1',{exact:true}).first().click()
 await page.getByLabel('Start beat, word 2',{exact:true}).fill('3')
 await page.getByRole('button',{name:'+ Save',exact:true}).click()
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('mm:user-songs')!)[0].arrangements[0].chordBars[0])
 expect(saved.tokens[1].startBeat).toBe(3)
 expect(saved.timingApproximate).toBe(false)
})
