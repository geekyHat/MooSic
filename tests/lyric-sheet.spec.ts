import {expect, test, openUserSong} from './fixtures/browser'

const source = '{c:Verse 1}\n[C]Ri[Am]cordo il mare[G]\n\n[Dm] [G]'

test('free song sheet saves sections and intraword/end anchors, reopens for editing and renders on mobile', async ({page}) => {
  await page.setViewportSize({width:375,height:900})
  await page.goto('/')
  await page.getByRole('button',{name:'Editor',exact:true}).click()
  await page.getByRole('button',{name:'+ New song',exact:true}).click()
  await page.getByLabel('Song name',{exact:true}).fill('Original sea study')
  await page.getByRole('button',{name:'Create',exact:true}).click()
  await page.getByRole('button',{name:/Chords \+ lyrics/}).click()
  await page.getByRole('button',{name:'Free song sheet',exact:true}).click()
  const input=page.getByRole('textbox',{name:'Song text with inline chords',exact:true})
  await input.fill(source)
  await expect(page.getByRole('region',{name:'Song sheet preview'})).toContainText('Verse 1')
  await expect(page.locator('.mm-lyrics-preview .chord-mark')).toHaveText(['C','Am','G','Dm','G'])
  await page.getByRole('button',{name:'+ Save',exact:true}).click()
  await expect(page.getByText('1 arrangement(s) saved',{exact:true})).toBeVisible()
  const saved=await page.evaluate(()=>{
    const song=JSON.parse(localStorage.getItem('mm:user-songs')!)[0]
    return {id:song.id,arr:song.arrangements[0]}
  })
  expect(saved.arr.chordBars).toEqual([])
  expect(saved.arr.lyricSheet.rows.map((r:{kind:string})=>r.kind)).toEqual(['section','line','spacer','line'])
  await page.reload()
  await page.getByRole('button',{name:'Editor',exact:true}).click()
  await page.getByRole('button',{name:/Original sea study/}).click()
  await page.getByRole('button',{name:'Edit',exact:true}).click()
  await expect(input).toHaveValue(source)
  await page.getByRole('button',{name:'Practice',exact:true}).last().click()
  await expect(page.locator('.mm-chord-sheet')).toContainText('Verse 1')
  const intraword=page.locator('.mm-chord-sheet .chord-mark[data-offset="2"]')
  await expect(intraword).toHaveText('Am')
  const onlyChords=page.locator('.mm-chord-sheet .mm-sheet-line').last().locator('.chord-mark')
  const firstChord=await onlyChords.first().boundingBox(), secondChord=await onlyChords.last().boundingBox()
  expect(secondChord!.x-firstChord!.x-firstChord!.width).toBeGreaterThanOrEqual(3)
  expect(await page.locator('.mm-chord-sheet .line-lyrics').first().locator('[data-lyric-fragment]').evaluateAll(elements=>elements.map(element=>element.textContent).join(''))).toBe('Ricordo il mare')
  const before=await intraword.boundingBox()
  await page.getByRole('slider',{name:'Scroll speed',exact:true}).focus()
  await page.keyboard.press('End')
  await expect(intraword).toBeVisible()
  expect((await intraword.boundingBox())?.x).toBe(before?.x)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.reload()
  await openUserSong(page,'Folk')
  await expect(page.locator('.mm-chord-sheet .chord-mark')).toHaveText(['C','Am','G','Dm','G'])
})

