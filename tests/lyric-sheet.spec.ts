 await page.addInitScript(song=>{if(!localStorage.getItem('mm:user-songs'))localStorage.setItem('mm:user-songs',JSON.stringify([song]))},fixture)
 await page.goto('/');await page.getByRole('button',{name:'Editor',exact:true}).click()
